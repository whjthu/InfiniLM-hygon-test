"""Exercise the original audit schema against bounded, explicit local fixtures."""
import copy
import json
from pathlib import Path
import struct
import subprocess
import sys
from tempfile import TemporaryDirectory
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parent))
import audit_once as A


def fixture_host_object(path, names):
    source, coff, elf = (path / name for name in ("fixture.cpp", "fixture.obj", "fixture.elf"))
    source.write_text("\n".join(f'extern "C" int {name}() {{ return {i + 12}; }}'
                              for i, name in enumerate(names)), encoding="utf-8")
    subprocess.run(["g++", "-c", str(source), "-o", str(coff)], check=True, timeout=20)
    subprocess.run(["objcopy", "-O", "elf64-x86-64", str(coff), str(elf)], check=True, timeout=15)
    data = bytearray(elf.read_bytes())
    # COFF does not carry ELF ST_SIZE. Supply test metadata from the real host
    # text offsets, while leaving machine code generated by the local compiler.
    off = struct.unpack_from("<Q", data, 40)[0]
    width, count = struct.unpack_from("<HH", data, 58)
    sections = [struct.unpack_from("<IIQQQQIIQQ", data, off + width * i) for i in range(count)]
    sym = next(row for row in sections if row[1] == 2)
    str_off, str_size = sections[sym[6]][4:6]
    symbols = {}
    for start in range(sym[4], sym[4] + sym[5], 24):
        pos, info, _, idx, value, _ = struct.unpack_from("<IBBHQQ", data, start)
        name = data[str_off + pos:data.index(0, str_off + pos, str_off + str_size)].decode("ascii", "replace")
        if name in names:
            assert info == 0x12
            symbols[start] = (idx, value)
    for start, (idx, value) in symbols.items():
        following = [v for i, v in symbols.values() if i == idx and v > value]
        size = min(following or [sections[idx][5]]) - value
        assert size > 0
        struct.pack_into("<Q", data, start + 16, size)
    return bytes(data)


def put(path, data):
    path.write_bytes((json.dumps(data, sort_keys=True) + "\n").encode("utf-8"))
    return A.sha(path.read_bytes())


def main():
    original_plan, helpers = A.load_scope(A.REPO)
    with TemporaryDirectory() as tmp:
        folder = Path(tmp)
        job, build = folder / "job", folder / "build"
        job.mkdir()
        build.mkdir()
        producer_path = folder / "producer-fixture.json"
        intent_path, ctrl_path, accounting = (job / s for s in ("intent.json", "controller.json", "accounting.tsv"))
        worker_path = build / "CPU-result.json"
        epoch = 1795200000.25
        intent = dict(epoch=epoch, deadline=epoch + 300, request=A.REQUEST, source_manifest_SHA256=A.MANIFEST,
                      claim_SHA256=A.CLAIM_SHA, parent=A.PARENT, node=A.NODE, replay_allowed=False)
        put(intent_path, intent)
        terminal = [A.PARENT + ".600", A.LABEL, "COMPLETED", "0:0", "9", A.NODE, "cpu=4,mem=8G,node=1"]
        controller = dict(request=A.REQUEST, accounting_columns=A.COLUMNS, actual_GPU_steps=0, state="COMPILE_VERIFIED",
                          terminal_visible=True, observations=[None, terminal], row=terminal)

        def account(row):
            accounting.write_bytes(("|".join(row) + "\n").encode())

        account(terminal)
        plan = copy.deepcopy(original_plan)
        cuda_header = plan["cuda_runtime_header"]
        fixture_producer = dict(actual_CPU="910407.1113", completed=True, passed=True,
                                all19_fresh_M_before_compile=True, all19_MD_equal_fresh_M=True,
                                fresh_dependencies_SHA256={str(i): {cuda_header: plan["cuda_runtime_header_SHA256"]}
                                                           for i in range(19)})
        plan["producer_SHA256"] = put(producer_path, fixture_producer)
        plan["producer_bytes"] = producer_path.stat().st_size
        metadata = f"{A.BASE}.o: {A.SOURCE} {cuda_header}\n"
        flags = plan["compiler_prefix"]
        outputs = {}
        worker = dict(label=A.LABEL, manifest_SHA256=A.MANIFEST, original_step=terminal[0], node=A.NODE, epoch=epoch,
                      deadline=epoch + 300, GRES="none", planned_device_TUs=1, actual_device_TUs=1,
                      actual_GPU_steps=0, explicit_Runtime_calls=0, completed=True, passed=True,
                      device_qualified=False, exports=sorted(A.EXPORTS), object=A.BASE + ".o",
                      dependencies_SHA256={A.SOURCE: plan["source_SHA256"], cuda_header: plan["cuda_runtime_header_SHA256"]},
                      commands=[])
        for label, args in (
                ("fresh-M", flags + ["-M", "-MF", A.BASE + ".before.d", "-MT", A.BASE + ".o", A.SOURCE]),
                ("compile", flags + ["-MD", "-MF", A.BASE + ".d", "-MT", A.BASE + ".o", "-c", A.SOURCE,
                                      "-o", A.BASE + ".o"]),
                ("symbols", ["/usr/bin/nm", "-g", "--defined-only", A.BASE + ".o"])):
            entry = dict(label=label, argv=args, returncode=0)
            for stream in ("stdout", "stderr"):
                raw = b""
                if (label, stream) == ("symbols", "stdout"):
                    raw = "".join(f"0000000000000000 T {x}\n" for x in sorted(A.EXPORTS)).encode()
                outputs[label, stream] = raw
                (build / f"{label}.{stream}").write_bytes(raw)
                entry[stream + "_SHA256"] = A.sha(raw)
            worker["commands"].append(entry)

        obj_path = build / "inverse_output_rope.o"
        md_path = build / "inverse_output_rope.d"
        before_path = build / "inverse_output_rope.before.d"
        real_host = fixture_host_object(folder, sorted(A.EXPORTS))
        obj_path.write_bytes(real_host)
        md_path.write_bytes(metadata.encode())
        before_path.write_bytes(metadata.encode())
        worker.update(object_SHA256=A.sha(real_host), fresh_M_SHA256=A.sha(metadata.encode()),
                      actual_MD_SHA256=A.sha(metadata.encode()))

        def seal():
            controller.update(receipt_SHA256=put(worker_path, worker), object_SHA256=worker["object_SHA256"])
            put(ctrl_path, controller)

        def invoke():
            with patch.object(A, "load_scope", return_value=(plan, helpers)):
                return A.audit(intent_path, ctrl_path, accounting, build, producer_path)

        def reject(expected):
            try:
                invoke()
            except ValueError as error:
                assert expected in str(error), (expected, str(error))
            else:
                raise AssertionError(expected)

        seal()
        positive = invoke()
        assert positive["passed"] and positive["qualified_compiler_objects"] == 1
        assert positive["embedded_uncompressed_AMDGPU_images"] == []
        assert not positive["device_ISA_independently_verified"]

        # The old controller would trust these matching report and byte pins.
        pseudo = b"self-reported genuine compile"
        obj_path.write_bytes(pseudo)
        worker["object_SHA256"] = A.sha(pseudo)
        seal()
        reject("HOST_RELOCATABLE_ELF")

        mismatched = fixture_host_object(folder, ["deep_inverse_rope_h1_v1", "different_function"])
        obj_path.write_bytes(mismatched)
        worker["object_SHA256"] = A.sha(mismatched)
        seal()
        reject("HOST_ELF_EXACT_TWO_WRAPPERS")
        obj_path.write_bytes(real_host)
        worker["object_SHA256"] = A.sha(real_host)

        bad = metadata.replace(cuda_header, "/opt/dtk/drifted.h").encode()
        md_path.write_bytes(bad)
        worker["actual_MD_SHA256"] = A.sha(bad)
        seal()
        reject("INDEPENDENT_M_MD_EQUALITY")
        md_path.write_bytes(metadata.encode())
        worker["actual_MD_SHA256"] = A.sha(metadata.encode())

        worker["dependencies_SHA256"][cuda_header] = "0" * 64
        seal()
        reject("INDEPENDENT_PRODUCER_DEPENDENCY_CLOSURE")
        worker["dependencies_SHA256"][cuda_header] = plan["cuda_runtime_header_SHA256"]

        worker["commands"][1]["argv"] = [x if x != "-arch=gfx936" else "-arch=gfx906"
                                          for x in worker["commands"][1]["argv"]]
        seal()
        reject("EXACT_GFX936_ARGUMENTS")
        worker["commands"][1]["argv"] = [x if x != "-arch=gfx906" else "-arch=gfx936"
                                          for x in worker["commands"][1]["argv"]]
        seal()

        accounting.write_bytes(("|".join(terminal) + "\n") .encode() * 2)
        reject("EXACT_ORIGINAL_NUMBERED_STEP")
        for state in ("RUNNING", "FAILED"):
            changed = terminal[:]
            changed[2:4] = [state, "1:0"]
            account(changed)
            if state == "RUNNING":
                reject("ORIGINAL_TERMINAL_RESOURCE_SCOPE")
            else:
                reject("CONTROLLER_TERMINAL_CONFLICT")
        controller.update(state="UNKNOWN", terminal_visible=False, row=None, observations=[None])
        put(ctrl_path, controller)
        failed = invoke()
        assert failed["planned_candidates"] == 2 and failed["qualified_compiler_objects"] == 0
        assert failed["outcome"] == "ORIGINAL_NONZERO_TERMINAL"

        account(terminal)
        eventual = invoke()
        assert eventual["passed"] and eventual["original_controller_state"] == "UNKNOWN"
    print(json.dumps(dict(real_host_objects_locally_compiled=2, positive_terminal_fixtures=2,
                          bad_receipt_or_object_rejections=8, original_nonzero_denominator_fixture=1,
                          synthetic_accounting_only=True, actual_target_terminal_consumed=0,
                          actual_gfx936_compiles=0, actual_gpu_steps=0), indent=2))


if __name__ == "__main__":
    main()
